int badge_tune_index_from_command(const char *command) {
    if (command[1] == '\0' && command[0] >= '1' &&
        command[0] < '1' + BADGE_TUNE_COUNT) {
        return command[0] - '1';
    }
    for (size_t i = 0; i < BADGE_TUNE_COUNT; ++i) {
        if (!strcmp(command, badge_tunes[i].command)) {
            return (int)i;
        }
    }
    if (!strcmp(command, "G-thang") || !strcmp(command, "g-thang")) {
        return BADGE_TUNE_G_THANG;
    }
    if (!strcmp(command, "jingle") || !strcmp(command, "startup-jingle") ||
        !strcmp(command, "startup jingle")) {
        return BADGE_TUNE_STARTUP_JINGLE;
    }
    return -1;
}
